    C(1) = -p.m2*p.a2*(dtheta_b^2 + dtheta1^2 + dtheta2^2 + 2*dtheta_b*dtheta1 ...
        + 2*dtheta_b*dtheta2 + 2*dtheta1*dtheta2) * cos(theta_b+theta1+theta2) ...
        - p.m1*p.a1*(dtheta_b^2 + dtheta1^2 + 2*dtheta_b*dtheta1)*cos(theta_b+theta1) ...
        - p.m2*p.l1*(dtheta_b^2 + dtheta1^2 + 2*dtheta_b*dtheta1)*cos(theta_b+theta1) ...
        - (p.m1+p.m2)*p.b_b*dtheta_b^2*cos(theta_b);
    C(2) = -p.m2*p.a2*(dtheta_b^2 + dtheta1^2 + dtheta2^2 + 2*dtheta_b*dtheta1 ...
        + 2*dtheta_b*dtheta2 + 2*dtheta1*dtheta2) * sin(theta_b+theta1+theta2) ...
        - p.m1*p.a1*(dtheta_b^2 + dtheta1^2 + 2*dtheta_b*dtheta1)*sin(theta_b+theta1) ...
        - p.m2*p.l1*(dtheta_b^2 + dtheta1^2 + 2*dtheta_b*dtheta1)*sin(theta_b+theta1) ...
        - (p.m1+p.m2)*p.b_b*dtheta_b^2*sin(theta_b);    
    C(3) = -p.m2*p.a2*p.b_b*((dtheta1^2 + dtheta2^2 + 2*dtheta1*dtheta2)*sin(theta1+theta2) ...
        + 2*dtheta_b*(dtheta1+dtheta2)*sin(theta1+theta2)) - p.m1*p.a1*p.b_b*dtheta1^2*sin(theta1) ...
        - p.m2*p.a2*p.l1*dtheta2^2*sin(theta2) - p.m2*p.b_b*p.l1*dtheta1^2*sin(theta1) ...
        - 2*p.m2*p.a2*p.l1*dtheta_b*dtheta2*sin(theta2) - 2*p.m2*p.a2*p.l1*dtheta1*dtheta2*sin(theta2) ...
        - 2*p.m2*p.b_b*p.l1*dtheta_b*dtheta1*sin(theta1) - 2*p.m1*p.a1*p.b_b*dtheta_b*dtheta1*sin(theta1);
    
    C(4) = p.m2*p.a2*p.b_b*dtheta_b^2*sin(theta1+theta2) +p.m1*p.a1*p.b_b*dtheta_b^2*sin(theta1) ...
        + p.m2*p.a2*p.l1*dtheta2^2*sin(theta2) + p.m2*p.b_b*p.l1*dtheta_b^2*sin(theta1) ...
        - 2*p.m2*p.a2*p.l1*dtheta_b*dtheta2*sin(theta2) - 2*p.m2*p.a2*p.l1*dtheta1*dtheta2*sin(theta2);
    
    C(5) = p.m2*p.a2*(p.b_b*dtheta_b^2*sin(theta1+theta2)+p.l1*(dtheta_b^2 ...
        + dtheta1^2 + 2*dtheta_b*dtheta1)*sin(theta2));
