        +p.b_b*p.b_b*(p.m1+p.m2)+p.l1*p.l1*p.m2+2*p.a2*p.b_b*p.m2*cos(theta1+theta2)...
        +2*p.a1*p.b_b*p.m1*cos(theta1)+2*p.a2*p.l1*p.m2*cos(theta2)...
        +2*p.b_b*p.l1*p.m2*cos(theta1);
