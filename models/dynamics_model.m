        +2*p.m2*cos(theta2)*p.a2*p.l1+p.b_b*p.m2*cos(theta1+theta2)*p.a2...
        +p.m2*p.l1*p.l1+p.b_b*p.m2*cos(theta1)*p.l1+p.I1+p.I2;
D(4,3) = D(3,4);
D(3,5) = p.I2+p.a2*p.a2*p.m2+p.a2*p.b_b*p.m2*cos(theta1+theta2)...
        +p.a2*p.l1*p.m2*cos(theta2);
D(5,3) = D(3,5);
D(4,4) = p.I1+p.I2+p.a1*p.a1*p.m1+p.m2*(p.a2*p.a2+2*cos(theta2)*p.a2*p.l1+p.l1*p.l1);
D(4,5) = p.m2*p.a2*p.a2+p.l1*p.m2*cos(theta2)*p.a2+p.I2;
D(5,4) = D(4,5);
D(5,5) = p.m2*p.a2*p.a2+p.I2;
%科氏力矩阵
