% dq = [dx_b, dy_b, dtheta_b, dtheta1, dtheta2]^T;

p = RobotParameters;
theta_b = q(3); theta1 = q(4); theta2 = q(5);
dtheta_b = dq(3); dtheta1 = dq(4); dtheta2 = dq(5);
    
% 惯性矩阵D(q)

D = zeros(5,5);

D(1,1) = p.m_b + p.m1 + p.m2;
D(2,2) = D(1,1);
D(1,3) = -p.m2*(p.l1*sin(theta_b+theta1) + p.b_b*sin(theta_b) ...
