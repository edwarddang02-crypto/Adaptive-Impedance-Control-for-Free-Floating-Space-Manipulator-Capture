D(5,1) = D(1,5);
D(2,3) = p.m2*(p.l1*cos(theta_b+theta1)+p.b_b*cos(theta_b)+p.a2*cos(theta_b+theta1+theta2))...
        +p.m1*(p.a1*cos(theta_b+theta1)+p.b_b*cos(theta_b));
D(3,2) = D(2,3);
